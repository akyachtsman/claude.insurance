// keep/views/help-view.js — the Help desk page (#/keep/help, feature 003).
//
// Ask a question in plain language, get an answer from the app's help guide and
// your own records. The page's job beyond rendering is FR-10 and FR-8's UI half:
// it labels every answer AI-generated and offers the broker channel, and it does
// so UNCONDITIONALLY — never off a flag the model controls. Of the three places
// the fact/advice boundary is defended (plan, Key decision 3), this is the ONLY
// independent one: the prompt rules and the shape of the grounding both resolve
// through the same single inference, so they lower the odds and cannot catch a
// violation. This file is what still holds when that inference goes wrong.
import { el, mount } from "../../dom.js";
import { icon } from "../../icons.js";
import { askHelp, loadHelpGuide, getUser, authEpoch, onAuthChange} from "../../supabase.js";
import {
  cleanQuestion, validateQuestion, suggestionChips, answerShape, creditedTopics,
} from "../logic/help.js";
import { page, originBackRow } from "./shell.js";

// FR-10's sentence, in ONE place. It is shown up front (before any question, so
// the client knows what they are reading before they type) and again on every
// answer. Two surfaces, one string — a label the user sees only after asking
// cannot inform the decision to ask.
const AI_NOTE =
  "Answers are AI-generated by Anthropic from this app's help guide and a summary " +
  "of your own records — check anything important with your broker.";

// The last answer, kept across navigations. FR-11 invites the client to follow a
// credited source to check it; the back control then promises "Back to help" —
// and the page they returned to was empty, because all state lived in this
// function's closure. Checking the answer cost the answer, and re-asking cost
// another paid call and one of twenty hourly slots.
//
// ⚠️ STAMPED WITH THE OWNER, and restored only to that owner. Module state
// outlives a sign-out: without this, signing out and signing in as someone else
// in the same tab showed the previous client's question, their answer, and their
// record lines under "Based on". This repo publishes three demo credentials and
// the login screen prefills one, so "a different person signs in on this
// machine" is the ordinary case, not a contrived one. Flagged by a security
// review of the commit that added the cache.
let lastAsk = null;


// ⚠️ THE BUSY GATE IS MODULE-LEVEL, and that is the point: `inFlight` below is
// per render, so it could not survive one. Start an ask, navigate away, come
// back before it settles — the new renderKeepHelp() builds a fresh `inFlight =
// null` with every control ENABLED, so a second submit launched a second
// provider call while the first was still running. Repeat the navigation and the
// client is billed for several answers and burns several throttle slots, while
// the UI claims one at a time.
// That harm was already written down a few lines below ("a second ask does not
// replace the first, it adds to it") — it was simply only solved WITHIN a
// render. Found by Codex.
// Keyed on the owner, not a bare boolean: if A's ask is still in flight when B
// signs in on the same tab, B must not be locked out of their own desk.
// Owners with a provider call in flight → the TOKEN of the ask that holds the
// slot. ⚠️ A MAP, NOT A SET, and the token is the whole of the difference.
//
// It was a set, and before that a single slot. The single slot was overwritten by
// the next client's ask (A asks, A signs out, B signs in and asks, A signs back
// in and asks — A's gate gone, two live calls, answers landing out of order).
// Keying on the owner fixed that and left a hole one layer down, **on the shared
// demo credential, where two different people ARE the same owner id**: A has an
// ask pending; A signs out, which clears this map; B signs in to the same account
// and asks, adding an entry under the identical id; A's response then settles and
// its `finally` deleted B's entry. The busy recompute right after reads the gate,
// finds it empty, and ENABLES B's form while B's own provider call is still
// running — so B submits again, the gate no longer refuses, and that is a second
// paid call, with the first `abort()` only cancelling B's browser fetch while the
// Edge Function bills on regardless. Found by Codex, round 21.
//
// ⚠️ THE COMMENT HERE ALREADY CLAIMED THE FIX: it opened "Carries `seq` so an
// earlier ask's completion cannot release a later one's gate" — a line left
// behind from the design the set replaced. The set carried no seq. A comment
// promising exactly the property the code dropped is the recurring defect of this
// PR, not an incident.
//
// So: `set(owner, token)` on entry, and the `finally` deletes **only if the
// token still matches**, which is false precisely when someone else has taken
// the slot. It does not depend on the login epoch moving — this PR's other
// lesson is that a guard resting on a second mechanism fails when that one does.
// Cross-owner is still handled by the owner captured before the await (S14).
const pendingByOwner = new Map();   // owner id -> token of the ask holding the slot
let askToken = 0;

// The Help view currently on screen. `ask()` renders its RESULT through this
// rather than through its own closures, because the render that started an ask
// may no longer be the one the client is looking at.
//
// ⚠️ THIS IS A CONSEQUENCE OF THE GATE ABOVE AND HAD TO BE HANDLED WITH IT.
// Navigating away mid-ask and back has always meant the answer renders into the
// FIRST render's nodes, which `mount()` has since detached — so it never reached
// the screen. That was survivable only because the second render's controls were
// enabled and the client could ask again; the gate removes that escape, and
// without this the client would wait, see the controls re-enable, and be shown
// nothing at all. The answer was already in `lastAsk`, so it appeared on the
// next visit to Help — which is not a defence of leaving it there.
let liveView = null;  // { renderAnswer, renderNotice, setBusy, input }

// ⚠️ THE EPOCH GUARDS WHAT IS WRITTEN AND RESTORED, NOT WHAT IS ALREADY HELD.
// A login change — here or in another tab — must drop this module's state
// outright, or A's question, answer and credited record values sit in memory and
// in a mounted view after the browser session stops being A's. `main.js`
// re-dispatches the route on the same signal, which replaces the DOM; this is
// the half that clears the references behind it. Found by Codex, round 19.
// ⚠️ THE TWO HALVES ARE NOT THE SAME STRENGTH ANY MORE, and the label was stale
// within one round. This used to read "THIS IS BELT — measured", because deleting
// the whole listener passed every scenario: `main.js`'s re-dispatch replaces the
// DOM and the epoch blocks the restore, so nothing was OBSERVABLE without it.
//
// `pendingByOwner.clear()` IS NOW LOAD-BEARING — mutation-tested, it fails S24.
// Once the gate holds a per-ask token (see its note), a departed client's slot is
// no longer released by their own settling ask, so without this clear the NEXT
// person on the shared credential inherits a disabled form and is locked out of
// the desk by a call that is not theirs. The fix that closed one hole made this
// line the thing standing between them and the lockout.
//
// `lastAsk = null` and `liveView = null` remain BELT, for the reason above, and
// are kept on data-hygiene grounds no UI test can express: without them the
// previous person's question, answer and credited record values stay in this
// module's memory after their session has ended.
// Labelling the two separately because this PR has twice had a comment call a
// guard belt after it had stopped being so, and both corrections came a round
// late.
onAuthChange(() => { lastAsk = null; liveView = null; pendingByOwner.clear(); });

// Which Help render is current. Bumped on entry, checked after the only await,
// so a render the client has navigated past cannot mount over what replaced it.
let helpRenderGen = 0;
// Parsed the way `main.js` parses it — strip the query, split, drop empties —
// rather than matched with a second regex that could disagree with the router
// about what a hash names. Same reasoning as `keepSubRoute` in shell.js, and it
// tolerates the trailing-slash and query-string forms for free.
// (It also avoids a false positive in check-undefined-calls.js, which reads
// `help(` inside a regex literal as a call to an undeclared `help`. Recorded in
// CLAUDE.md: the guard's own comment says it under-reports rather than cry wolf,
// and on regex literals it does the opposite.)
const onHelp = () =>
  location.hash.replace(/^#/, "").split("?")[0].split("/").filter(Boolean)[1] === "help";

export async function renderKeepHelp() {
  const gen = ++helpRenderGen;
  const guide = await loadHelpGuide();

  // ⚠️ TWO WAYS THIS RENDER IS ALREADY OBSOLETE, and both end with `mount()`
  // replacing a page the client is actually on while the URL names a different
  // route. `loadHelpGuide()` fetches the corpus on the FIRST Help visit, and
  // nothing cancels this function when the route changes under it. Found by
  // Codex, against the commit that made this render also register `liveView` —
  // so a stale render could additionally become the target for an in-flight
  // answer.
  //   · The client left Help entirely. A newer route has mounted; `helpRenderGen`
  //     is untouched because nothing called THIS function again, so only the
  //     hash can tell.
  //   · A newer Help render started (away and straight back) and may already
  //     have mounted. The hash still says Help, so only the generation can tell.
  // Both checks, because neither covers the other.
  if (gen !== helpRenderGen) return;
  if (!onHelp()) return;

  const input = el("input", {
    class: "k-help__input",
    attrs: { type: "text", placeholder: "Ask a question…", "aria-label": "Ask a question", autocomplete: "off" },
  });
  const submit = el("button", { class: "k-btn k-help__ask", attrs: { type: "submit" } }, [el("span", { text: "Ask" })]);
  const error = el("p", { class: "k-error", attrs: { role: "alert" } });
  const answerRegion = el("div", { class: "k-help__out", attrs: { "aria-live": "polite" } }, [
    el("p", { class: "k-help__ai", text: AI_NOTE }),
  ]);

  // One in-flight request at a time. A second ask aborts the first rather than
  // racing it — two answers arriving out of order would render the older one.
  let inFlight = null;

  // The chips are disabled too, not just the input and the button. Aborting the
  // in-flight request only drops the BROWSER's side of it: the Edge Function has
  // already reserved a throttle row and may have started the provider call, and
  // that keeps running. So a second ask does not replace the first, it adds to
  // it — the UI said "one in flight" while the client was billed for several and
  // burned several throttle slots. Populated by renderChips() below, which runs
  // after this is defined.
  const chipButtons = [];
  function setBusy(busy) {
    submit.disabled = busy;
    input.disabled = busy;
    for (const b of chipButtons) b.disabled = busy;
    submit.querySelector("span").textContent = busy ? "Asking…" : "Ask";
  }

  function renderNotice(shaped) {
    answerRegion.replaceChildren(
      el("div", { class: "k-help__notice" }, [
        icon("alert", { size: 18 }),
        el("p", { text: shaped.notice }),
      ]),
      // The standing label lives IN this region, so replacing the region removed
      // it — leaving the failure state as the one screen with no AI-generated
      // line on it. Re-rendered rather than moved out, so there is still exactly
      // one on screen in every state.
      el("p", { class: "k-help__ai", text: AI_NOTE }),
    );
  }

  function renderAnswer(shaped, question) {
    const used = creditedTopics(guide, shaped.topics);
    const blocks = [
      el("p", { class: "k-help__q", text: question }),
      // `white-space: pre-line` in keep.css — the answer may carry line breaks
      // and collapsing them would run separate points together.
      el("div", { class: "k-help__a" }, [el("p", { text: shaped.answer })]),
    ];

    // FR-11: name what it drew on, so the client can check it.
    if (used.length || shaped.records.length) {
      blocks.push(el("div", { class: "k-help__src" }, [
        el("div", { class: "k-lbl", text: "Based on" }),
        ...used.map((t) => el("a", { class: "k-ilink", attrs: { href: t.route }, text: t.title })),
        ...shaped.records.map((r) => el("span", { class: "k-imuted", text: r })),
      ]));
    }

    // FR-8's hand-off, on EVERY answer. Nothing reads `reason === "refused"` here
    // and nothing should: the model sets it, so gating the remedy on it let a
    // model answer a coverage question AND attach "this needs your broker"
    // underneath, which reads as broker-endorsed. The trailer still carries it
    // and the payload still reports it — for logging and for anyone auditing how
    // often the boundary fires — but it decides nothing the client sees.
    //
    // That flag is model-controlled end to end: the model emits the REFUSED
    // marker, the function turns it into `reason: "refused"`, help.js turns that
    // into `brokerHandoff`, and this block appeared. Both error directions are
    // reachable and one is worse than having no hand-off at all:
    //   · declines in prose, omits the marker → the client is refused with no
    //     broker channel, so FR-8's remedy is silently absent;
    //   · answers a coverage question AND emits the marker → "This one needs your
    //     broker" renders UNDERNEATH a coverage determination, which reads as
    //     broker-endorsed. Measured. And a client can ask for that marker.
    // Unconditional removes both, and a standing "your broker can put it in
    // writing" is the right thing on an insurance help desk anyway. `reason`
    // still carries the distinction for anyone who needs it; nothing the model
    // says decides what the client is offered.
    blocks.push(el("div", { class: "k-help__broker" }, [
      el("p", { text: "Coverage questions — whether something is covered, or whether a limit is enough — are your broker's to answer in writing." }),
      el("a", { class: "k-ilink", attrs: { href: "#/keep/insurance" }, text: "Open a policy to send a request" }),
    ]));

    // FR-10, rendered on EVERY answer regardless of what came back. A model that
    // ignored its instructions cannot remove this line, which is the point.
    blocks.push(el("p", { class: "k-help__ai", text: AI_NOTE }));
    answerRegion.replaceChildren(...blocks);
  }

  async function ask(raw) {
    // cleanQuestion, NOT the raw value: validate and send the SAME string, so the
    // length the client reports is the length the server enforces
    // (`handler.ts`'s QUESTION_MAX, measured after its own trim).
    //
    // ⚠️ This comment previously described a `help_queries` CHECK constraint
    // capping the RAW text, and a correction was then inserted INTO THE MIDDLE OF
    // ITS SENTENCE, leaving "…so validating one / ⚠️ … / string and sending
    // another…". Both the constraint and the column are gone, and a half-applied
    // fix reads worse than the stale text it was patching.
    const question = cleanQuestion(raw);
    const v = validateQuestion(question);
    error.textContent = v.ok ? "" : v.error;
    if (!v.ok) { input.focus(); return; }

    // ⚠️ THE OWNER IS CAPTURED HERE, BEFORE THE AWAIT — not read after it. This
    // line used to be `owner: getUser()?.id` down beside the cache write, and
    // that is a cross-client disclosure, not a tidiness point: the provider call
    // runs for up to 60s and nothing aborts it when the client signs out (only a
    // NEWER ask aborts, via the controller below). So client A asks, signs out,
    // client B signs in on the same tab before the call returns — and the cache
    // stamped A's question, answer and credited RECORD VALUES with B's id, after
    // which the restore check below matched for B and showed them to B.
    // Found by Codex. It is the same hole a security review caught once already
    // (the cache originally carried no owner at all, which is why the stamp
    // exists); reading the stamp a tick too late reopened it, which is why S14
    // now drives the whole race with a held response rather than asserting on
    // the field's presence.
    const asker = getUser()?.id ?? null;
    // The LOGIN this ask belongs to, not just the account. See `authEpoch`.
    const askEpoch = authEpoch();
    // REFUSE rather than supersede. Superseding still bills the first call — the
    // Edge Function keeps going whatever the browser does — so the only thing
    // that actually protects spend is not sending the second one.
    if (pendingByOwner.has(asker)) return;
    const token = ++askToken;
    pendingByOwner.set(asker, token);

    if (inFlight) inFlight.abort();
    const controller = new AbortController();
    inFlight = controller;
    setBusy(true);
    // The AI label rides along: replacing the whole region removed it for the
    // length of the request (up to the provider timeout), while this file's own
    // header and S10 both describe it as unconditional. "Unconditional" has to
    // include the state the client spends the most time looking at.
    answerRegion.replaceChildren(
      el("p", { class: "k-imuted", text: "Looking…" }),
      el("p", { class: "k-help__ai", text: AI_NOTE }),
    );

    let payload;
    try {
      payload = await askHelp(question, { signal: controller.signal });
    } finally {
      // Release on EVERY exit, including a throw. `askHelp` has a catch-all and
      // returns a shaped payload rather than throwing, so this is insurance
      // against that contract changing — not a live case. It matters because a
      // leaked gate is not a glitch: it locks the client out of the desk
      // entirely until they reload the page.
      //
      // ⚠️ ONLY IF THIS ASK STILL HOLDS THE SLOT. An unconditional delete here
      // released the NEXT person's gate on the shared credential — see the note
      // on `pendingByOwner`. Nothing accumulates either way: whoever holds the
      // slot deletes it on their own exit.
      if (pendingByOwner.get(asker) === token) pendingByOwner.delete(asker);
    }
    inFlight = null;

    // ⚠️ RECOMPUTED FROM THE GATE — not set to false, and NOT SKIPPED on the
    // mismatch paths below. This has now been wrong twice in opposite
    // directions. Round 14: `setBusy(false)` ran before the owner check, so a
    // departed client's completion RE-ENABLED the current client's form while
    // their own call was in flight. Round 17 moved it after the checks, which
    // fixed that and created the mirror image: A asks, signs out, B signs into
    // the same shared account and opens Help — the owner-keyed gate disables B's
    // view, the `finally` above releases it, but the epoch mismatch returned
    // before any setBusy, so B's controls stayed disabled until they navigated
    // away and back. Found by Codex both times.
    // Reading the gate answers both: B is enabled iff B has nothing in flight.
    // It also makes the aborted path correct for free — a newer ask holds the
    // gate, so the busy state stays.
    const who = getUser()?.id ?? null;
    (liveView ?? { setBusy }).setBusy(Boolean(who) && pendingByOwner.has(who));

    if (controller.signal.aborted) return;        // superseded by a newer ask

    // ⚠️ THE OWNER CHECK COMES BEFORE setBusy, AND THE ORDER IS THE WHOLE POINT.
    // It used to sit after it, so a departed client's completion unconditionally
    // RE-ENABLED the current client's controls — while that client's own request
    // was still in flight. The gate then silently refused their submit, leaving
    // an enabled form that did nothing: the worst of both, since the client can
    // see no reason it is not working. Found by Codex, on the commit that
    // introduced `liveView`.
    // The client who asked is no longer the client who is here: do not touch
    // their controls, do not cache this answer and do not render it. `lastAsk`
    // is deliberately left alone rather than cleared — whatever the CURRENT
    // client has is theirs, and wiping it would let a departed client's
    // in-flight request delete it.
    //
    // ⚠️ THIS LINE WAS LABELLED "BELT, NOT THE FIX" AND THAT IS NO LONGER TRUE.
    // It was accurate when the only thing downstream was the cache write: the
    // capture of `asker` above was what closed the disclosure, and a mutation
    // removing this check still passed S14, so it was honestly marked as defence
    // in depth. Moving `setBusy` below it made it load-bearing in its own right
    // — it is now the only thing stopping a departed client's completion from
    // re-enabling the current client's controls — and S14 fails without it.
    // Left as a record because a comment that keeps calling a guard redundant
    // after it stopped being redundant is how a later edit deletes it.
    // ⚠️ THE EPOCH IS THE GUARD THAT MATTERS HERE, and the owner comparison is
    // what it replaced as the primary. The login screen prefills one shared demo
    // credential, so A can sign out and B sign back into the SAME account in the
    // same tab — `getUser()?.id` is then still equal to `asker`, this check used
    // to pass, and A's question, answer and credited record values rendered for
    // B. Signing out did not protect them.
    //
    // ⚠️ THE OWNER COMPARISON BELOW IS NOW SUBSUMED, and stating that here rather
    // than discovering it later is the point: mutation testing confirms that
    // deleting it — here AND in the restore check — passes every scenario,
    // because every identity change goes through `signIn`/`signOut` and both bump
    // the epoch. It is kept against a FORESEEABLE change rather than a
    // hypothetical one: a third auth entry point (a magic link, a re-auth on
    // refresh) that forgets to bump would leave the epoch equal across two
    // different clients, and then this line is the only thing left. That is the
    // one case it still covers; it covers nothing else, and it is not what fixed
    // the shared-account defect.
    if (authEpoch() !== askEpoch) return;
    if ((getUser()?.id ?? null) !== asker) return;

    // Through liveView: this render may be the detached one. `??` falls back to
    // our own closures so a single render (the ordinary case) is unchanged.
    const view = liveView ?? { renderAnswer, renderNotice, input };

    const shaped = answerShape(payload);
    lastAsk = { shaped, question, owner: asker, epoch: askEpoch };
    if (shaped.ok) view.renderAnswer(shaped, question); else view.renderNotice(shaped);
    // The ask box of the view on screen, not of the render that asked.
    if (view.input !== input) view.input.value = question;

    // Disabling the focused control drops focus to <body>, and nothing put it
    // back — so after one question a keyboard or screen-reader user had to tab
    // from the top of the page (bar, nav, search, two menus) to ask another.
    // Restored only when WE are the ones who dropped it: if the reader has tabbed
    // somewhere else while waiting, stealing focus back is worse than the bug.
    if (document.activeElement === document.body) view.input.focus();
  }

  const form = el("form", { class: "k-help__form", attrs: { novalidate: "novalidate" },
    on: { submit: (e) => { e.preventDefault(); ask(input.value); } } }, [input, submit]);

  // `k-chiprow` / `k-chiptog` are the Keep's existing pill-button recipe (hover,
  // 44px target, disabled state). Reused rather than restyled: a second chip
  // class drifts from the first the moment either is touched.
  const chips = suggestionChips(guide);
  chipButtons.push(...chips.map((c) =>
    el("button", { class: "k-chiptog", attrs: { type: "button" },
      // The `disabled` set by setBusy() stops this firing at all; the guard is
      // belt and braces for a click already dispatched when it was set.
      on: { click: () => { if (inFlight) return; input.value = c.ask; ask(c.ask); } }, text: c.ask })));
  const chipRow = chipButtons.length
    ? el("div", { class: "k-chiprow k-help__chips" }, chipButtons)
    : null;

  // `mid` (880px): an answer is prose, and prose set to the Keep's full 1200px
  // measure runs past a comfortable line length — the ask box stretches with it
  // and ends up a 1100px-wide single-line input. Measured at 1280px before the
  // change.
  // Restore the last answer before mounting, so returning from a credited link
  // shows what you left rather than an empty page — but only to the person who
  // asked it. A null owner on either side never matches, which is the safe
  // direction: it costs a restore, not a disclosure.
  const me = getUser()?.id ?? null;
  // A render that arrives mid-ask shows the ask as in progress, rather than
  // offering controls that would launch a second paid call. This is the half of
  // the module-level gate the client can see.
  if (me && pendingByOwner.has(me)) setBusy(true);
  // Registered AFTER the restore check so a render that throws before this point
  // cannot become the target for an in-flight answer.
  liveView = { renderAnswer, renderNotice, setBusy, input };
  // Same reasoning as the completion guard: a COMPLETED answer must not outlive
  // the login that asked for it either, or signing out leaves it on screen for
  // the next person to sign into the same account.
  if (lastAsk && me && lastAsk.owner === me && lastAsk.epoch === authEpoch()) {
    input.value = lastAsk.question;
    if (lastAsk.shaped.ok) renderAnswer(lastAsk.shaped, lastAsk.question); else renderNotice(lastAsk.shaped);
  }

  mount(page("help", [
    originBackRow(),
    el("h1", { class: "k-h1", text: "Help" }),
    el("p", { class: "k-sub", text: "Ask about anything in the Keep — I'll point you to the right screen, or read back what's on your file." }),
    chipRow,
    form,
    error,
    answerRegion,
  ], { mid: true }));
}
